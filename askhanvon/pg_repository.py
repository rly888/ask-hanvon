    def events_query(self, event_type="", since="", user_id=None, limit=1000):
        with self._tx() as c:
            if event_type and since and user_id is not None:
                return [dict(r) for r in c.execute(
                    "SELECT * FROM events WHERE event_type=%s AND ts>=%s"
                    " AND user_id=%s ORDER BY id LIMIT %s",
                    (event_type, since, user_id, limit)).fetchall()]
            if event_type and since:
                return [dict(r) for r in c.execute(
                    "SELECT * FROM events WHERE event_type=%s AND ts>=%s"
                    " ORDER BY id LIMIT %s", (event_type, since, limit)).fetchall()]
            if since:
                return [dict(r) for r in c.execute(
                    "SELECT * FROM events WHERE ts>=%s ORDER BY id LIMIT %s",
                    (since, limit)).fetchall()]
            return [dict(r) for r in c.execute(
                "SELECT * FROM events ORDER BY id DESC LIMIT %s", (limit,)).fetchall()]

    def events_count(self, event_type, since=""):
        with self._tx() as c:
            if since:
                rows = [dict(r) for r in c.execute(
                    "SELECT COUNT(*) AS n FROM events WHERE event_type=%s AND ts>=%s",
                    (event_type, since)).fetchall()]
            else:
                rows = [dict(r) for r in c.execute(
                    "SELECT COUNT(*) AS n FROM events WHERE event_type=%s",
                    (event_type,)).fetchall()]
        return rows[0]["n"] if rows else 0

