    def touch_session(self, session_id, title="") -> None:
        with self._tx() as c:
            if title:
                c.execute(
                    "UPDATE chat_sessions SET updated_at=%s,"
                    " title=CASE WHEN title='' THEN %s ELSE title END WHERE id=%s",
                    (now_iso(), title[:40], session_id),
                )
            else:
                c.execute(
                    "UPDATE chat_sessions SET updated_at=%s WHERE id=%s",
                    (now_iso(), session_id),
                )

