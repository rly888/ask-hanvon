        with self._tx() as c:
            c.execute("DELETE FROM chat_messages WHERE session_id=%s", (session_id,))
            c.execute("DELETE FROM memory_short WHERE session_id=%s", (session_id,))
            c.execute("DELETE FROM chat_sessions WHERE id=%s", (session_id,))

