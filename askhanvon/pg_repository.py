    # ---------- 记忆 ----------
    def mem_short_get(self, session_id, key):
        with self._tx() as c:
            rows = [dict(r) for r in c.execute(
                "SELECT value, expires_at FROM memory_short"
                " WHERE session_id=%s AND key=%s", (session_id, key)).fetchall()]
        if not rows:
            return None
        if rows[0]["expires_at"] and rows[0]["expires_at"] < time.time():
            return None
        return rows[0]["value"]

