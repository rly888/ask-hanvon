    def event_enqueue(self, payload) -> int:
        with self._tx() as c:
            cur = c.execute(
                "INSERT INTO event_queue(payload, status, created_at)"
                " VALUES(%s, 'new', %s) RETURNING id",
                (payload, now_iso()),
            )
            return cur.fetchone()["id"]

    def event_claim_batch(self, limit=200, lease_seconds=300.0):
        deadline = time.time() - lease_seconds
        with self._tx() as c:
            cur = c.execute(
                "UPDATE event_queue SET status='processing', claimed_at=%s"
                " WHERE id IN (SELECT id FROM event_queue"
                " WHERE status='new'"
                " OR (status='processing' AND (claimed_at IS NULL OR claimed_at < %s))"
                " ORDER BY id LIMIT %s)"
                " RETURNING id, payload",
                (time.time(), deadline, limit),
            )
            return [dict(r) for r in cur.fetchall()]

    def event_mark_done(self, ids) -> None:
        with self._tx() as c:
            for i in ids:
                c.execute(
                    "UPDATE event_queue SET status='done', consumed_at=%s WHERE id=%s",
                    (now_iso(), i),
                )

    def event_release(self, ids) -> None:
        with self._tx() as c:
            for i in ids:
                c.execute(
                    "UPDATE event_queue SET status='new', claimed_at=NULL WHERE id=%s",
                    (i,),
                )

